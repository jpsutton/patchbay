/// Agents that take instructions through a system-prompt hook (`code::agents::session_meta`,
/// `CODEX_CONFIG`). Every other agent gets the block as a preamble on every prompt instead.
pub fn has_prompt_hook(kind: AgentKind) -> bool {
    matches!(kind, AgentKind::Grok | AgentKind::ClaudeCode | AgentKind::Antigravity | AgentKind::Codex)
}

/// Role instructions, then the team's project rules, then a short generated block, for the team
/// `session_id` belongs to. None when it is on no live team.
pub fn instructions_for(data_dir: &Path, db: &Db, session_id: &str) -> Option<String> {
    // No teams.db yet means no teams; don't create one just to look.
    if !data_dir.join("teams.db").is_file() {
        return None;
    }
    match build_instructions(data_dir, db, session_id) {
        Ok(t) => t,
        Err(e) => {
            tracing::warn!("team instructions for {session_id}: {e:#}");
            None
        }
    }
}

fn build_instructions(data_dir: &Path, db: &Db, session_id: &str) -> Result<Option<String>> {
    let tdb = TeamsDb::open(data_dir)?;
    let Some((team, me)) = tdb.membership(session_id)? else { return Ok(None) };
    let role = tdb.role(&me.role_id)?;
    let tpl = tdb.template(&team.template_id)?;
    let roles = tdb.roles()?;
    let mut out = String::new();
    out.push_str(role.instructions.trim());
    if !team.project_rules.trim().is_empty() {
        out.push_str("\n\nProject rules:\n");
        out.push_str(team.project_rules.trim());
    }
    out.push_str(&format!("\n\nYou are on team \"{}\" as {} (seat {}).\nRoster:\n", team.slug, role.name, me.seat));
    for m in tdb.members(&team.id)? {
        let rname = roles.iter().find(|r| r.id == m.role_id).map_or("?", |r| r.name.as_str());
        let s = db.get_code_session(&m.session_id)?;
        let (title, agent) = s.map_or(("(session gone)".into(), String::new()), |s| {
            let t = clean(&dispatch::strip_forged_tags(&s.title));
            let t = cap_chars(&t, 80).to_owned();
            (t, s.agent)
        });
        let you = if m.session_id == session_id { " (you)" } else { "" };
        out.push_str(&format!("- {rname}: \"{title}\" {agent}, session {}{you}\n", m.session_id));
    }
    if !tpl.routing.is_empty() {
        out.push_str("Decisions go by class:\n");
        for r in &tpl.routing {
            out.push_str(&format!("- {}: {} ({})\n", r.class, r.goes_to, r.examples));
        }
    }
    out.push_str(
        "Tools: team_roster, team_send (by role or session id), item_list, item_get; roles with the right capability also get item_add, item_set, item_note, decision_open and decision_answer, and the host refuses the rest. send_agent_message and list_agent_sessions work as usual.\nIf your earlier context was summarized or lost, re-read the board with item_list before acting.",
    );
    Ok(Some(out))
}

/// The block as a preamble for an agent without a prompt hook, or None.
pub fn preamble_for(data_dir: &Path, db: &Db, session_id: &str) -> Option<String> {
    let s = db.get_code_session(session_id).ok()??;
    if AgentKind::parse(&s.agent).is_some_and(has_prompt_hook) {
        return None;
    }
    let block = instructions_for(data_dir, db, session_id)?;
    Some(format!("<team-instructions>\n{block}\n</team-instructions>"))
}


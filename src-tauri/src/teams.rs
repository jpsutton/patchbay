fn role_seed(id: &str, name: &str, standing: bool, caps: Caps, reports_to: Option<&str>, instructions: &str) -> Role {
    Role {
        id: id.into(),
        name: name.into(),
        standing,
        instructions: instructions.into(),
        caps,
        reports_to: reports_to.map(Into::into),
        builtin: true,
        updated_at: 0,
    }
}


/// `path` made absolute with symlinks resolved as far as it exists; the missing tail is kept as is.
///
/// On Windows, `canonicalize` returns a `\\?\` verbatim path. Git (and several other tools) reject
/// those when creating worktrees, so an accepted drive/UNC prefix is stripped before the path is
/// returned or stored. Unknown `\\?\` namespaces fail closed.
fn resolve(path: &Path) -> Result<PathBuf> {
    let mut tail = Vec::new();
    let mut cur = path.to_path_buf();
    loop {
        if let Ok(c) = cur.canonicalize() {
            let stripped = strip_windows_verbatim(c)
                .ok_or_else(|| anyhow!("unresolvable Windows path namespace for {}", path.display()))?;
            return Ok(tail.iter().rev().fold(stripped, |acc, t| acc.join(t)));
        }
        match (cur.file_name().map(|n| n.to_owned()), cur.parent().map(Path::to_path_buf)) {
            (Some(n), Some(p)) => {
                tail.push(n);
                cur = p;
            }
            _ => return Ok(path.to_path_buf()),
        }
    }
}

/// Drop an accepted Windows `\\?\` / `\\?\UNC\` prefix from a canonical path so git and other tools
/// accept it. Other `\\?\` namespaces (Volume GUID, HarddiskVolume, bare) are unresolvable → `None`.
fn strip_windows_verbatim(path: PathBuf) -> Option<PathBuf> {
    #[cfg(windows)]
    {
        return strip_windows_verbatim_str(&path.to_string_lossy()).map(PathBuf::from);
    }
    #[cfg(not(windows))]
    {
        Some(path)
    }
}

/// Pure string form of [`strip_windows_verbatim`] (testable on every OS).
fn strip_windows_verbatim_str(s: &str) -> Option<String> {
    let Some(rest) = s.strip_prefix(r"\\?\") else {
        return Some(s.to_owned());
    };
    if let Some(unc) = rest.strip_prefix(r"UNC\") {
        let mut parts = unc.split('\\');
        let server = parts.next().unwrap_or("");
        let share = parts.next().unwrap_or("");
        if server.is_empty() || share.is_empty() {
            return None;
        }
        return Some(format!(r"\\{unc}"));
    }
    let b = rest.as_bytes();
    if b.len() >= 2 && b[0].is_ascii_alphabetic() && b[1] == b':' {
        if b.len() == 2 {
            return Some(rest.to_owned());
        }
        if b[2] == b'\\' || b[2] == b'/' {
            return Some(rest.to_owned());
        }
    }
    None
}

/// A branch name safe to hand to git later: no leading `-`, and git accepts it as a branch.
fn check_pr_base(name: &str) -> Result<()> {
    let ok = !name.starts_with('-')
        && std::process::Command::new("git").args(["check-ref-format", "--branch", name]).output().is_ok_and(|o| o.status.success());
    if !ok {
        bail!("{name:?} is not a usable branch name");
    }
    Ok(())
}

/// Control characters (newlines included) become spaces, so event text can't forge lines.
fn clean(t: &str) -> String {
    t.chars().map(|c| if c.is_control() { ' ' } else { c }).collect()
}

fn cap_chars(s: &str, max_chars: usize) -> &str {
    match s.char_indices().nth(max_chars) {
        None => s,
        Some((idx, _)) => &s[..idx],
    }
}

fn cap_bytes(s: &str, max_bytes: usize) -> &str {
    if s.len() <= max_bytes {
        s
    } else {
        let mut cut = max_bytes;
        while !s.is_char_boundary(cut) {
            cut -= 1;
        }
        &s[..cut]
    }
}

/// Refuse an export folder that is, or holds as one of our three files, a symlink; one whose
/// LEDGER.md or ROSTER.md was not written by us (say, a real Hub desk); or one inside the team's
/// folder or worktree root, where an agent could write into it.
fn check_export_dir(dir: &Path, cwd: &Path, worktree_root: &Path) -> Result<()> {
    let is_link = |p: &Path| std::fs::symlink_metadata(p).is_ok_and(|m| m.file_type().is_symlink());
    if is_link(dir) {
        bail!("{} is a symlink; pick a real export folder", dir.display());
    }
    let real = resolve(dir)?;
    for root in [cwd, worktree_root] {
        if !root.as_os_str().is_empty() && real.starts_with(root) {
            bail!("the export folder must be outside the team folder {}", root.display());
        }
    }
    for name in ["LEDGER.md", "ROSTER.md", "CHANGELOG.md"] {
        let p = dir.join(name);
        if is_link(&p) {
            bail!("{} is a symlink; pick another export folder", p.display());
        }
    }
    for name in ["LEDGER.md", "ROSTER.md"] {
        let p = dir.join(name);
        if let Ok(text) = std::fs::read_to_string(&p)
            && !text.starts_with(GENERATED)
        {
            bail!("{} exists and was not generated by Patchbay; pick another export folder", p.display());
        }
    }
    Ok(())
}

/// Rewrite LEDGER.md and ROSTER.md and append `event` to CHANGELOG.md. Failure is logged, not
/// raised: the export is a convenience and must not undo a change that already happened.
fn export(tdb: &TeamsDb, db: &Db, team_id: &str, event: &str) {
    if let Err(e) = write_export(tdb, db, team_id, event) {
        tracing::warn!("team export: {e:#}");
    }
}

fn write_export(tdb: &TeamsDb, db: &Db, team_id: &str, event: &str) -> Result<()> {
    let team = tdb.team(&team_id)?;
    if team.export_dir.trim().is_empty() {
        return Ok(());
    }
    let dir = PathBuf::from(&team.export_dir);
    check_export_dir(&dir, &resolve(Path::new(&team.cwd))?, &team.effective_worktree_root()?)?;
    std::fs::create_dir_all(&dir)?;
    let roles = tdb.roles()?;
    let mut roster = format!("{GENERATED}\n# Roster: {}\n\nFolder: {}\n\n| Role | Seat | Session | Agent |\n|---|---|---|---|\n", team.slug, team.cwd);
    for m in tdb.members(team_id)? {
        let role = roles.iter().find(|r| r.id == m.role_id).map_or("?", |r| r.name.as_str());
        let (title, agent) = db.get_code_session(&m.session_id)?.map_or((String::new(), String::new()), |s| (s.title, s.agent));
        roster.push_str(&format!("| {role} | {} | {} ({}) | {agent} |\n", m.seat, clean(&title).replace('|', "/"), m.session_id));
    }
    write_file(&dir.join("ROSTER.md"), &roster)?;
    write_file(&dir.join("LEDGER.md"), &ledger(tdb, &team)?)?;
    let log = dir.join("CHANGELOG.md");
    let mut text = std::fs::read_to_string(&log).unwrap_or_else(|_| format!("{GENERATED}\n# Changelog: {}\n\n", team.slug));
    text.push_str(&format!("- {} {}\n", chrono::Utc::now().format("%Y-%m-%d %H:%M:%SZ"), clean(event)));
    write_file(&log, &text)?;
    Ok(())
}

/// Write `text` to `path`, refusing a symlink at the path itself (checked by the open, so a link
/// swapped in after `check_export_dir` is still refused). Not on Windows: there the check above
/// is all there is.
fn write_file(path: &Path, text: &str) -> Result<()> {
    use std::io::Write;
    let mut o = std::fs::OpenOptions::new();
    o.write(true).create(true).truncate(true);
    #[cfg(unix)]
    std::os::unix::fs::OpenOptionsExt::custom_flags(&mut o, libc::O_NOFOLLOW);
    o.open(path).with_context(|| format!("can't write {}", path.display()))?.write_all(text.as_bytes())?;
    Ok(())
}

/// LEDGER.md: items by status, then the decisions still open.
fn ledger(tdb: &TeamsDb, team: &Team) -> Result<String> {
    let mut out = format!("{GENERATED}\n# Ledger: {}\n\n", team.slug);
    let items = tdb.items(&team.id, None)?;
    if items.is_empty() {
        out.push_str("No items yet.\n");
    }
    for status in items::STATUSES {
        let here: Vec<_> = items.iter().filter(|i| i.status == *status).collect();
        if here.is_empty() {
            continue;
        }
        out.push_str(&format!("## {status}\n\n| Id | Title | Type | Severity | Assignee | PR |\n|---|---|---|---|---|---|\n"));
        for i in here {
            let cell = |t: &str| clean(&t.replace('|', "/"));
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} |\n",
                i.id, cell(&i.title), cell(&i.kind), cell(&i.severity), i.member_session.as_deref().unwrap_or(""), i.pr_url.as_deref().unwrap_or("")
            ));
        }
        out.push('\n');
    }
    let open: Vec<_> = tdb.decisions(&team.id)?.into_iter().filter(|d| d.status.starts_with("awaiting")).collect();
    if !open.is_empty() {
        out.push_str("## Decisions waiting\n\n");
        for d in open {
            out.push_str(&format!("- {} ({}, {}): {}\n", d.id, d.class, d.status, clean(&d.question)));
        }
    }
    Ok(out)
}


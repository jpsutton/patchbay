// ---------------- instructions ----------------

/// Agents that take instructions through a system-prompt hook (`code::agents::session_meta`,
/// `CODEX_CONFIG`). Every other agent gets the block as a preamble on peer messages instead.
pub fn has_prompt_hook(kind: AgentKind) -> bool {
    matches!(kind, AgentKind::Grok | AgentKind::ClaudeCode | AgentKind::Antigravity | AgentKind::Codex)
}

/// Role instructions, then the team's project rules, then a short generated block, for the team
/// `session_id` belongs to. None when it is on no live team.
pub fn instructions_for(data_dir: &Path, db: &Db, session_id: &str) -> Option<String> {
    // No teams.db yet means no teams; don't create one just to look.
    if !data_dir.join("teams.db").is_file() {
        return None;
    }
    match build_instructions(data_dir, db, session_id) {
        Ok(t) => t,
        Err(e) => {
            tracing::warn!("team instructions for {session_id}: {e:#}");
            None
        }
    }
}

fn build_instructions(data_dir: &Path, db: &Db, session_id: &str) -> Result<Option<String>> {
    let tdb = TeamsDb::open(data_dir)?;
    let Some((team, me)) = tdb.membership(session_id)? else { return Ok(None) };
    let role = tdb.role(&me.role_id)?;
    let tpl = tdb.template(&team.template_id)?;
    let roles = tdb.roles()?;
    let mut out = String::new();
    out.push_str(role.instructions.trim());
    if !team.project_rules.trim().is_empty() {
        out.push_str("\n\nProject rules:\n");
        out.push_str(team.project_rules.trim());
    }
    out.push_str(&format!("\n\nYou are on team \"{}\" as {} (seat {}).\nRoster:\n", team.slug, role.name, me.seat));
    for m in tdb.members(&team.id)? {
        let rname = roles.iter().find(|r| r.id == m.role_id).map_or("?", |r| r.name.as_str());
        let s = db.get_code_session(&m.session_id)?;
        let (title, agent) = s.map_or(("(session gone)".into(), String::new()), |s| (s.title, s.agent));
        let you = if m.session_id == session_id { " (you)" } else { "" };
        out.push_str(&format!("- {rname}: \"{title}\" {agent}, session {}{you}\n", m.session_id));
    }
    if !tpl.routing.is_empty() {
        out.push_str("Decisions go by class:\n");
        for r in &tpl.routing {
            out.push_str(&format!("- {}: {} ({})\n", r.class, r.goes_to, r.examples));
        }
    }
    out.push_str(
        "Tools: message teammates with send_agent_message (session ids above); list_agent_sessions shows what they are doing.",
    );
    Ok(Some(out))
}

/// The block as a preamble for an agent without a prompt hook, or None.
pub fn preamble_for(data_dir: &Path, db: &Db, session_id: &str) -> Option<String> {
    let s = db.get_code_session(session_id).ok()??;
    if AgentKind::parse(&s.agent).is_some_and(has_prompt_hook) {
        return None;
    }
    let block = instructions_for(data_dir, db, session_id)?;
    Some(format!("<team-instructions>\n{block}\n</team-instructions>"))
}

// ---------------- markdown export ----------------

/// Refuse a folder whose LEDGER.md or ROSTER.md was not written by us (say, a real Hub desk).
fn check_export_dir(dir: &Path) -> Result<()> {
    for name in ["LEDGER.md", "ROSTER.md"] {
        let p = dir.join(name);
        if let Ok(text) = std::fs::read_to_string(&p)
            && !text.starts_with(GENERATED)
        {
            bail!("{} exists and was not generated by Patchbay; pick another export folder", p.display());
        }
    }
    Ok(())
}

/// Rewrite LEDGER.md and ROSTER.md and append `event` to CHANGELOG.md. Failure is logged, not
/// raised: the export is a convenience and must not undo a change that already happened.
fn export(tdb: &TeamsDb, db: &Db, team_id: &str, event: &str) {
    if let Err(e) = write_export(tdb, db, team_id, event) {
        tracing::warn!("team export: {e:#}");
    }
}

fn write_export(tdb: &TeamsDb, db: &Db, team_id: &str, event: &str) -> Result<()> {
    let team = tdb.team(&team_id)?;
    let dir = PathBuf::from(&team.export_dir);
    check_export_dir(&dir)?;
    std::fs::create_dir_all(&dir)?;
    let roles = tdb.roles()?;
    let mut roster = format!("{GENERATED}\n# Roster: {}\n\nFolder: {}\n\n| Role | Seat | Session | Agent |\n|---|---|---|---|\n", team.slug, team.cwd);
    for m in tdb.members(team_id)? {
        let role = roles.iter().find(|r| r.id == m.role_id).map_or("?", |r| r.name.as_str());
        let (title, agent) = db.get_code_session(&m.session_id)?.map_or((String::new(), String::new()), |s| (s.title, s.agent));
        roster.push_str(&format!("| {role} | {} | {title} ({}) | {agent} |\n", m.seat, m.session_id));
    }
    std::fs::write(dir.join("ROSTER.md"), roster)?;
    std::fs::write(dir.join("LEDGER.md"), format!("{GENERATED}\n# Ledger: {}\n\nNo items yet.\n", team.slug))?;
    let log = dir.join("CHANGELOG.md");
    let mut text = std::fs::read_to_string(&log).unwrap_or_else(|_| format!("{GENERATED}\n# Changelog: {}\n\n", team.slug));
    text.push_str(&format!("- {} {event}\n", chrono::Utc::now().format("%Y-%m-%d %H:%M:%SZ")));
    std::fs::write(log, text)?;
    Ok(())
}


//! Teams (docs/design/teams.md, phase 1): Code sessions filling named roles on one project.
//!
//! State lives in its own `teams.db` beside `patchbay.sqlite`, with its own `user_version` and
//! migration list, so it never collides with `db::MIGRATIONS`. Phase 1 is read-mostly: roles and
//! templates (built-ins), teams, members attached by hand, role instructions delivered to the
//! member's agent, and a one-way markdown export.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, anyhow, bail};
use rusqlite::{Connection, OptionalExtension, params};
use serde::{Deserialize, Serialize};

use crate::code::agents::AgentKind;
use crate::db::{Db, new_id, now_ms};
use crate::{AppState, CmdError, CmdResult, session_activity};

const MIGRATIONS: &[&str] = &[r#"
CREATE TABLE roles (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    standing INTEGER NOT NULL,
    instructions TEXT NOT NULL,
    caps_json TEXT NOT NULL,
    reports_to TEXT,
    builtin INTEGER NOT NULL DEFAULT 0,
    updated_at INTEGER NOT NULL
);
CREATE TABLE templates (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    seats_json TEXT NOT NULL,
    routing_json TEXT NOT NULL,
    updated_at INTEGER NOT NULL
);
CREATE TABLE teams (
    id TEXT PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    template_id TEXT NOT NULL REFERENCES templates(id),
    cwd TEXT NOT NULL,
    id_prefix TEXT NOT NULL,
    pr_base TEXT NOT NULL,
    worktree_root TEXT NOT NULL,
    project_rules TEXT NOT NULL,
    export_dir TEXT NOT NULL,
    created_at INTEGER NOT NULL,
    archived_at INTEGER
);
CREATE TABLE members (
    team_id TEXT NOT NULL REFERENCES teams(id),
    session_id TEXT NOT NULL,
    seat TEXT NOT NULL,
    role_id TEXT NOT NULL REFERENCES roles(id),
    status TEXT NOT NULL,
    item_id TEXT,
    joined_at INTEGER NOT NULL,
    left_at INTEGER
);
-- A session fills one seat at a time.
CREATE UNIQUE INDEX members_active ON members(session_id) WHERE left_at IS NULL;
"#];

/// First line of every exported file; `write_export` never overwrites a file without it.
const GENERATED: &str = "<!-- Generated by Patchbay Teams. Edits are overwritten; nothing reads this file back. -->";

#[derive(Serialize, Deserialize, Clone, Default, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Caps {
    pub writes_items: bool,
    pub dispatches: bool,
    pub decides: bool,
    pub merges: bool,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Role {
    pub id: String,
    pub name: String,
    pub standing: bool,
    pub instructions: String,
    pub caps: Caps,
    pub reports_to: Option<String>,
    pub builtin: bool,
    pub updated_at: i64,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Choice {
    pub agent: String,
    pub model: Option<String>,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Seat {
    /// Key within the template ("desk", "workers").
    pub seat: String,
    pub role_id: String,
    pub agent: String,
    pub model: Option<String>,
    pub permission_mode: String,
    /// Standing seats: how many members. Worker seats: the pool size.
    pub count: u32,
    /// Agent/model choices the desk picks from for a worker seat.
    #[serde(default)]
    pub choices: Vec<Choice>,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Route {
    pub class: String,
    pub goes_to: String,
    pub examples: String,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Template {
    pub id: String,
    pub name: String,
    pub seats: Vec<Seat>,
    pub routing: Vec<Route>,
    pub updated_at: i64,
}

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Team {
    pub id: String,
    pub slug: String,
    pub template_id: String,
    pub cwd: String,
    pub id_prefix: String,
    pub pr_base: String,
    pub worktree_root: String,
    pub project_rules: String,
    pub export_dir: String,
    pub created_at: i64,
    pub archived_at: Option<i64>,
}

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Member {
    pub team_id: String,
    pub session_id: String,
    pub seat: String,
    pub role_id: String,
    pub status: String,
    pub item_id: Option<String>,
    pub joined_at: i64,
    pub left_at: Option<i64>,
}

